// Writes docs/api-reference.md from the API routes themselves (CLAUDE.md, Documentation): each
// src/app/api/**/route.ts starts with a comment saying what it does, and exports its HTTP methods.
// `npm run docs:api` after changing a route; tests/unit/api-docs.test.ts fails while the file is stale.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const API = join(root, "src", "app", "api");
const OUT = join(root, "..", "docs", "api-reference.md");

function routeFiles(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) return routeFiles(p);
    return name === "route.ts" ? [p] : [];
  });
}

/** The doc comment directly above the first export (// lines or a /** block), as plain text. */
export function routeComment(source) {
  const lines = source.split(/\r?\n/);
  const first = lines.findIndex((l) => /^export /.test(l));
  const block = [];
  for (let i = first - 1; i >= 0; i--) {
    const l = lines[i].trim();
    if (l.startsWith("//") || l.startsWith("*") || l.startsWith("/**")) block.unshift(l);
    else break;
  }
  return block
    .map((l) => l.replace(/^\/\*\*\s?|^\*\/$|^\*\s?|^\/\/\s?/, "").replace(/\s*\*\/$/, ""))
    .filter((l, i, all) => l !== "" || (i > 0 && i < all.length - 1))
    .join("\n")
    .trim();
}

/** The HTTP methods a route exports (function or const). */
export function routeMethods(source) {
  const found = new Set();
  for (const m of source.matchAll(/^export (?:async function|const|function) (GET|POST|PUT|PATCH|DELETE)\b/gm)) found.add(m[1]);
  return [...found];
}

/** "/api/games/[slug]" → "/api/games/{slug}" */
const urlOf = (file) => "/api/" + relative(API, dirname(file)).replace(/\\/g, "/").replace(/\[([^\]]+)\]/g, "{$1}");

export function buildApiDocs() {
  const routes = routeFiles(API)
    .map((f) => {
      const src = readFileSync(f, "utf8");
      return { url: urlOf(f), methods: routeMethods(src), doc: routeComment(src), file: relative(join(root, ".."), f).replace(/\\/g, "/") };
    })
    .sort((a, b) => a.url.localeCompare(b.url));
  const body = routes
    .map((r) => `## \`${r.methods.join(" · ")} ${r.url}\`\n\n${r.doc || "_(no description: add a comment above the first export)_"}\n\nSource: [\`${r.file}\`](../${r.file})\n`)
    .join("\n");
  return `# API reference

GENERATED by \`web/scripts/build-api-docs.mjs\` from the route files — don't edit by hand; run \`npm run docs:api\`
in \`web/\`. The request and response details of the public games API are in [06-api-spec.md](06-api-spec.md).
Everything else (pages, forms) goes through server actions, listed there too.

${body}`;
}

if (process.argv[1]?.endsWith("build-api-docs.mjs")) {
  writeFileSync(OUT, buildApiDocs());
  console.log(`docs/api-reference.md written (${routeFiles(API).length} routes)`);
}
