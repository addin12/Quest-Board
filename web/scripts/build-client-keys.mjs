// Which UI strings the browser needs: every key that client code (a "use client" file, or anything in
// src/components, which client files import) names literally, plus whole groups whose keys are built at
// run time. The root layout sends only these with each page (round 36: about half of all strings).
//
//   npm run i18n:client-keys      → writes src/lib/i18n/client-keys.ts
//
// tests/unit/client-keys.test.ts fails when the file is out of date (a new t("…") in client code).
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

/**
 * Key groups client code builds at run time: errors and validation messages that server actions return,
 * and t(`cover.${…}`), t(`feedback.kind.${…}`), t(`tz.${…}`), genreLabelKey, styleLabelKey, reasonKey, targetKey.
 */
export const DYNAMIC_PREFIXES = ["err.", "v.", "cover.", "feedback.kind.", "tz.", "genre.", "style.", "report.reason.", "report.target."];

const root = join(import.meta.dirname, "..");
const walk = (dir, out = []) => {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (/\.tsx?$/.test(name)) out.push(p);
  }
  return out;
};

/** The sorted list of keys the browser needs, from the source as it is now. */
export function computeClientKeys() {
  const en = readFileSync(join(root, "src/lib/i18n/en.ts"), "utf8");
  const all = [...en.matchAll(/^ {2}"([^"]+)": /gm)].map((m) => m[1]);
  const known = new Set(all);
  const start = walk(join(root, "src")).filter((f) => {
    const rel = relative(root, f).replace(/\\/g, "/");
    return rel.startsWith("src/components/") || readFileSync(f, "utf8").startsWith('"use client"');
  });
  // …and every src/lib module those files import, directly or through each other (e.g. lib/quiz.ts).
  const files = new Set(start);
  const queue = [...start];
  while (queue.length) {
    const f = queue.pop();
    for (const m of readFileSync(f, "utf8").matchAll(/from\s+"(@\/lib\/[^"]+|\.\.?\/[^"]+)"/g)) {
      const base = m[1].startsWith("@/") ? join(root, "src", m[1].slice(2)) : join(f, "..", m[1]);
      const hit = [base, `${base}.ts`, `${base}.tsx`, join(base, "index.ts")].find((p) => { try { return statSync(p).isFile(); } catch { return false; } });
      if (!hit || files.has(hit) || !relative(root, hit).replace(/\\/g, "/").startsWith("src/lib/")) continue;
      if (/\/i18n\/(en|id|dict|client-keys)\.ts$/.test(hit.replace(/\\/g, "/"))) continue; // the dictionaries themselves
      files.add(hit);
      queue.push(hit);
    }
  }
  const keys = new Set(all.filter((k) => DYNAMIC_PREFIXES.some((p) => k.startsWith(p))));
  for (const f of files) {
    for (const m of readFileSync(f, "utf8").matchAll(/["'`]([a-zA-Z]+\.[\w.-]+)["'`]/g)) if (known.has(m[1])) keys.add(m[1]);
  }
  return [...keys].sort();
}

if (process.argv[1]?.endsWith("build-client-keys.mjs")) {
  const keys = computeClientKeys();
  const out = `// GENERATED by scripts/build-client-keys.mjs — do not edit (npm run i18n:client-keys).
// The UI strings client code uses: the root layout sends only these with each page.
export const CLIENT_KEYS: readonly string[] = ${JSON.stringify(keys, null, 0).replace(/","/g, '",\n  "').replace(/^\[/, "[\n  ").replace(/\]$/, ",\n]")};
`;
  writeFileSync(join(root, "src/lib/i18n/client-keys.ts"), out);
  console.log(`${keys.length} client keys written to src/lib/i18n/client-keys.ts`);
}
