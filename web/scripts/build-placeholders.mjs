// ── helpers ──────────────────────────────────────────────────────────────
function rng(seed) {
  let h = 2166136261;
  for (const c of seed) h = Math.imul(h ^ c.charCodeAt(0), 16777619);
  return () => {
    h = (h + 0x6d2b79f5) | 0;
    let t = Math.imul(h ^ (h >>> 15), 1 | h);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const hsl = (h, s, l, a = 1) => `hsl(${((h % 360) + 360) % 360} ${s}% ${l}% / ${a})`;
const f = (n) => Math.round(n * 10) / 10;

function linear(id, stops, x2 = 0, y2 = 1) {
  return `<linearGradient id="${id}" x1="0" y1="0" x2="${x2}" y2="${y2}">${stops
    .map(([o, c]) => `<stop offset="${o}" stop-color="${c}"/>`)
    .join("")}</linearGradient>`;
}
function radial(id, stops) {
  return `<radialGradient id="${id}">${stops.map(([o, c]) => `<stop offset="${o}" stop-color="${c}"/>`).join("")}</radialGradient>`;
}
function stars(r, n, maxY, color = "#fff") {
  let s = "";
  for (let i = 0; i < n; i++) s += `<circle cx="${f(r() * W)}" cy="${f(r() * maxY)}" r="${f(0.6 + r() * 1.8)}" fill="${color}" opacity="${f(0.3 + r() * 0.7)}"/>`;
  return s;
}
/** Jagged ridge from x=0..W around baseY, closed to the bottom. */
function ridge(r, baseY, amp, step, color) {
  let d = `M0 ${H} L0 ${baseY}`;
  for (let x = 0; x <= W + step; x += step) d += ` L${x} ${f(baseY - r() * amp)}`;
  return `<path d="${d} L${W} ${H} Z" fill="${color}"/>`;
}
/** Smooth rolling hills. */
function hills(r, baseY, amp, color, bumps = 4) {
  const seg = W / bumps;
  let d = `M0 ${H} L0 ${baseY}`;
  for (let i = 0; i < bumps; i++) {
    const x0 = i * seg;
    d += ` Q${f(x0 + seg / 2)} ${f(baseY - amp * (0.5 + r()))} ${f(x0 + seg)} ${f(baseY - r() * amp * 0.3)}`;
  }
  return `<path d="${d} L${W} ${H} Z" fill="${color}"/>`;
}
function svg(w, h, defs, body, title) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" preserveAspectRatio="xMidYMid slice" role="img" aria-label="${title}">
<!-- Original placeholder art generated by scripts/build-placeholders.mjs (Quest Board). -->
<defs>${defs}</defs>
${body}
</svg>
`;
}

